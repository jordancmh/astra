package com.astra.engine.routing;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;

import java.time.Instant;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;

@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
class NegotiationEventRepositoryTest {

    @Autowired
    private NegotiationEventRepository repository;

    @Test
    void saveAndFindById_persistsEventWithAutoGeneratedIdAndTimestamp() {
        NegotiationEvent event = new NegotiationEvent();
        event.setAnomalyId("D-001");
        event.setVehicleId("V-004");
        event.setAffectedRoutes("RT-003, RT-004");
        event.setEventMessage("V-004 granted primary detour via Federal Hwy (Priority 5); V-005 assigned NPE corridor.");

        NegotiationEvent saved = repository.save(event);

        assertThat(saved.getId()).isNotNull();
        assertThat(saved.getCreatedAt()).isNotNull();

        Optional<NegotiationEvent> found = repository.findById(saved.getId());
        assertThat(found).isPresent();
        assertThat(found.get().getAnomalyId()).isEqualTo("D-001");
        assertThat(found.get().getVehicleId()).isEqualTo("V-004");
        assertThat(found.get().getAffectedRoutes()).isEqualTo("RT-003, RT-004");
        assertThat(found.get().getEventMessage()).contains("Federal Hwy");
    }

    @Test
    void findByVehicleIdOrderByCreatedAtDesc_returnsSortedEvents() {
        NegotiationEvent e1 = new NegotiationEvent(
                "D-001", "V-005", "RT-004", "Conceded detour to V-004", Instant.now().minusSeconds(10)
        );
        repository.save(e1);

        NegotiationEvent e2 = new NegotiationEvent(
                "D-002", "V-005", "RT-004", "Rerouted around congestion", Instant.now()
        );
        repository.save(e2);

        List<NegotiationEvent> events = repository.findByVehicleIdOrderByCreatedAtDesc("V-005");
        assertThat(events).hasSize(2);
        assertThat(events.get(0).getEventMessage()).isEqualTo("Rerouted around congestion");
    }
}
